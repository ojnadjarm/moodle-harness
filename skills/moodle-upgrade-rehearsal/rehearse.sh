#!/usr/bin/env bash
# Timed Moodle upgrade rehearsal (default 4.5 -> 5.3) on a throwaway upstream site.
# Usage: rehearse.sh {up|run|rollback|report|down|all} [--out FILE]
set -euo pipefail

R="${REHEARSAL_DIR:-$HOME/moodle-envs/4.5-rehearsal}"
P="${REHEARSAL_PROJECT:-moodle45r}"
PORT="${REHEARSAL_PORT:-8145}"
FROM_BRANCH="${FROM_BRANCH:-MOODLE_405_STABLE}" FROM_PHP="${FROM_PHP:-8.3}" FROM_PG="${FROM_PG:-13}"
TO_BRANCH="${TO_BRANCH:-MOODLE_503_STABLE}" TO_PHP="${TO_PHP:-8.4}" TO_PG="${TO_PG:-17}"
SIZE="${REHEARSAL_SIZE:-XS}"
OUT="$HOME/drop/money/samples/rehearsal-4.5-to-5.3.md"
T="$R/timings.tsv"

cmd="${1:-}"; shift || true
[ "${1:-}" = --out ] && OUT="$2"

guard() {
    local real; real="$(realpath -m "$R")"
    case "$real" in "$HOME/moodle-envs/4.5"|"$HOME/moodle-envs/vass"*|"$HOME/moodle-envs/5."*|"$HOME/moodle-envs/shared")
        echo "refused: $real is a real env" >&2; exit 1 ;; esac
    case "$P" in moodle4[0-9]|moodle5[0-9]|moodle-shared|vass*) echo "refused: project $P is a real env" >&2; exit 1 ;; esac
}
dc() { docker compose -p "$P" --project-directory "$R" -f "$R/docker-compose.yml" "$@"; }
app() { dc exec -T app "$@"; }
now() { printf '%s' "$EPOCHREALTIME"; }
# step <phase> <name> <command...>: run, append seconds to timings.tsv, stop on failure.
step() {
    local phase="$1" name="$2"; shift 2
    local t0 t1 rc=0; t0=$(now)
    echo "== $phase / $name" >&2
    set +e; ( set -e; "$@" ); rc=$?; set -e
    t1=$(now)
    printf '%s\t%s\t%.1f\t%s\n' "$phase" "$name" "$(echo "$t1 - $t0" | bc)" "$([ $rc = 0 ] && echo ok || echo "fail($rc)")" >> "$T"
    [ $rc = 0 ] || { echo "step $name failed ($rc)" >&2; exit $rc; }
}
setenv() { sed -i "s|^$1=.*|$1=$2|" "$R/.env"; }
cfgdb() { sed -i "s|^\$CFG->dbhost .*|\$CFG->dbhost    = '$1';|" "$R/site/config.php"; }
release() { app php -r 'define("CLI_SCRIPT",1); require "config.php"; echo $CFG->release, " theme=", $CFG->theme, " db=", $DB->get_server_info()["version"], " php=", PHP_VERSION;'; }
pass() { cat "$R/admin.pass"; }

clone() { [ -d "$R/src/$1" ] || git -c http.version=HTTP/1.1 clone -q --branch "$1" --depth 1 https://github.com/moodle/moodle.git "$R/src/$1"; }
fetch() { clone "$FROM_BRANCH" & clone "$TO_BRANCH" & wait -n && wait -n; }
start() { dc up -d && waitdb "db$FROM_PG"; }

compose_file() {
    cat > "$R/.env" <<EOF
PHP=$FROM_PHP
DOCROOT=/var/www/html
EOF
    cat > "$R/docker-compose.yml" <<EOF
# Throwaway upgrade-rehearsal site, generated by moodle-upgrade-rehearsal/rehearse.sh. Remove with: rehearse.sh down
services:
  db$FROM_PG:
    image: postgres:$FROM_PG
    environment: {POSTGRES_USER: moodle, POSTGRES_PASSWORD: moodle, POSTGRES_DB: moodle}
    volumes: [db$FROM_PG:/var/lib/postgresql/data]
  db$TO_PG:
    image: postgres:$TO_PG
    profiles: [target]
    environment: {POSTGRES_USER: moodle, POSTGRES_PASSWORD: moodle, POSTGRES_DB: moodle}
    volumes: [db$TO_PG:/var/lib/postgresql/data]
  app:
    image: moodlehq/moodle-php-apache:\${PHP}
    environment: {APACHE_DOCUMENT_ROOT: "\${DOCROOT}"}
    ports: ["127.0.0.1:$PORT:80"]
    volumes: [./site:/var/www/html, ./moodledata:/var/www/moodledata]
volumes: {db$FROM_PG: {}, db$TO_PG: {}}
EOF
}

config_php() {
    cat > "$R/site/config.php" <<EOF
<?php
unset(\$CFG);
global \$CFG;
\$CFG = new stdClass();
\$CFG->dbtype    = 'pgsql';
\$CFG->dblibrary = 'native';
\$CFG->dbhost    = 'db$FROM_PG';
\$CFG->dbname    = 'moodle';
\$CFG->dbuser    = 'moodle';
\$CFG->dbpass    = 'moodle';
\$CFG->prefix    = 'mdl_';
\$CFG->dboptions = ['dbpersist' => 0, 'dbport' => '', 'dbsocket' => ''];
\$CFG->wwwroot   = 'http://localhost:$PORT';
\$CFG->dataroot  = '/var/www/moodledata';
\$CFG->admin     = 'admin';
\$CFG->directorypermissions = 0777;
\$CFG->debug = E_ALL;
\$CFG->debugdisplay = 0;
require_once(__DIR__ . '/lib/setup.php');
EOF
}

waitdb() { for _ in $(seq 1 60); do dc exec -T "$1" pg_isready -h 127.0.0.1 -U moodle -q && return 0; sleep 1; done; return 1; }

install_site() {
    [ -f "$R/admin.pass" ] || { (umask 077; echo "Rh-$(openssl rand -hex 6)!" > "$R/admin.pass"); }
    app php admin/cli/install_database.php --lang=en --adminuser=admin --adminpass="$(pass)" \
        --adminemail=admin@example.com --fullname="Upgrade rehearsal" --shortname=rehearsal --agree-license >/dev/null
}
seed() {
    app php admin/cli/cfg.php --name=theme --set=classic
    app php admin/tool/generator/cli/maketestsite.php --size="$SIZE" --fixeddataset --bypasscheck --quiet >/dev/null
}

# smoke <docroot-label>: GET login, POST admin creds, expect a logged-in page; prints the theme in use.
smoke() {
    local jar tok page; jar="$(mktemp)"
    tok=$(curl -fsS -c "$jar" "http://localhost:$PORT/login/index.php" | sed -n 's/.*name="logintoken" value="\([^"]*\)".*/\1/p' | head -1)
    [ -n "$tok" ] || { echo "no logintoken"; return 1; }
    page=$(curl -fsSL -b "$jar" -c "$jar" --data-urlencode "username=admin" --data-urlencode "password=$(pass)" \
        --data-urlencode "logintoken=$tok" "http://localhost:$PORT/login/index.php")
    rm -f "$jar"
    grep -q 'login/logout.php' <<<"$page" || { echo "login failed"; return 1; }
    echo "login ok, theme in page: $(grep -oE 'styles\.php/[a-z_]+' <<<"$page" | head -1 | cut -d/ -f2)"
}

backup() {
    mkdir -p "$R/backup"
    dc exec -T "db$FROM_PG" pg_dump -U moodle -Fc moodle > "$R/backup/db.dump"
    app tar -C /var/www -czf - moodledata > "$R/backup/moodledata.tgz"
    tar -C "$R" -czf "$R/backup/code.tgz" site
    ls -la "$R/backup" | awk 'NR>1{print $5, $9}'
}
db_move() {
    dc --profile target up -d "db$TO_PG" && waitdb "db$TO_PG"
    dc exec -T "db$TO_PG" pg_restore -U moodle -d moodle --no-owner < "$R/backup/db.dump"
    cfgdb "db$TO_PG"
}
code_swap() {
    mv "$R/site" "$R/site-old"
    cp -a "$R/src/$TO_BRANCH" "$R/site"
    cp -p "$R/site-old/config.php" "$R/site/config.php"
    # Add-on plugins would be copied here: core 5.1+ keeps them under public/.
}
docroot() {
    setenv PHP "$TO_PHP"; setenv DOCROOT /var/www/html/public
    dc up -d --force-recreate app
}
upgrade() { app php admin/cli/upgrade.php --non-interactive; }
theme_check() {
    local theme; theme=$(app php admin/cli/cfg.php --name=theme)
    echo "theme setting: $theme; classic code present: $(app test -d public/theme/classic && echo yes || echo no)"
    if ! app test -d "public/theme/$theme"; then
        app php admin/cli/cfg.php --name=theme --set=boost
        app php admin/cli/purge_caches.php
        echo "theme moved $theme -> boost"
    fi
}

restore() {
    dc stop app
    rm -rf "$R/site" "$R/site-old"
    tar -C "$R" -xzf "$R/backup/code.tgz"
    dc exec -T "db$FROM_PG" sh -c 'dropdb -U moodle moodle && createdb -U moodle moodle'
    dc exec -T "db$FROM_PG" pg_restore -U moodle -d moodle --no-owner < "$R/backup/db.dump"
    setenv PHP "$FROM_PHP"; setenv DOCROOT /var/www/html
    dc up -d --force-recreate app
    app sh -c 'rm -rf /var/www/moodledata/* && tar -C /var/www -xzf -' < "$R/backup/moodledata.tgz"
    dc --profile target stop "db$TO_PG"
}

report() {
    mkdir -p "$(dirname "$OUT")"
    local tot up rb
    tot=$(awk -F'\t' '$1=="upgrade"{s+=$3} END{printf "%.0f", s/60+0.4999}' "$T")
    up=$(awk -F'\t' '$1=="upgrade"{s+=$3} END{printf "%.1f", s/60}' "$T")
    rb=$(awk -F'\t' '$1=="rollback"{s+=$3} END{printf "%.1f", s/60}' "$T")
    {
        echo "# Upgrade rehearsal: Moodle 4.5 -> 5.3 (throwaway upstream site)"
        echo
        echo "Measured $(date +%F) by rehearse.sh on the fleet laptop. Upgrade wall $tot min ($up min measured, maintenance window), rollback $rb min."
        echo
        echo "| Phase | Step | Seconds | Result |"
        echo "|---|---|---:|---|"
        awk -F'\t' '{printf "| %s | %s | %s | %s |\n", $1, $2, $3, $4}' "$T"
        echo
        echo "## Scope"
        echo "- Upstream core only, no add-on plugins, $SIZE generator data ($(du -h "$R/backup/db.dump" | cut -f1) DB dump, $(du -h "$R/backup/moodledata.tgz" | cut -f1) moodledata). A customer site adds plugin swaps, its theme rebuild and DB-size-dependent dump/restore and upgrade time."
        echo "- Sites below 4.4 need one extra hop (to 4.5) first: a second upgrade.php run of the same kind."
        echo "- Steps: maintenance on, backup, pg$FROM_PG -> pg$TO_PG (5.3 needs PostgreSQL 17), code swap, /public docroot + PHP $TO_PHP, upgrade.php, theme check, smoke login; rollback restores the backup and logs in again."
        echo
        echo "## Notes"
        cat "$R/notes.md" 2>/dev/null || true
    } > "$OUT"
    echo "report: $OUT"
}

guard
case "$cmd" in
    up)
        mkdir -p "$R/src" "$R/moodledata"; chmod 777 "$R/moodledata"; : > "$T"; : > "$R/notes.md"
        step setup "fetch 4.5 + 5.3 code" fetch
        rm -rf "$R/site"; cp -a "$R/src/$FROM_BRANCH" "$R/site"; compose_file; config_php
        step setup "start containers" start
        step setup "install 4.5 site" install_site
        step setup "seed: Classic theme + $SIZE test site" seed
        echo "- Before: $(release)" >> "$R/notes.md"
        ;;
    run)
        step upgrade "maintenance on" app php admin/cli/maintenance.php --enable
        step upgrade "backup (db dump, moodledata, code)" backup
        step upgrade "db move pg$FROM_PG -> pg$TO_PG" db_move
        step upgrade "code swap" code_swap
        step upgrade "/public docroot + PHP $TO_PHP" docroot
        step upgrade "admin/cli/upgrade.php" upgrade
        step upgrade "theme check" theme_check > "$R/theme.log"
        sed 's/^/- Theme: /' "$R/theme.log" >> "$R/notes.md"
        step upgrade "maintenance off" app php admin/cli/maintenance.php --disable
        step upgrade "smoke login" smoke > "$R/smoke.log"
        echo "- After: $(release); smoke: $(cat "$R/smoke.log")" >> "$R/notes.md"
        ;;
    rollback)
        step rollback "restore code, db, moodledata" restore
        step rollback "maintenance off (backup was taken inside the window)" app php admin/cli/maintenance.php --disable
        step rollback "smoke login" smoke > "$R/smoke-rollback.log"
        echo "- Rolled back: $(release); smoke: $(cat "$R/smoke-rollback.log")" >> "$R/notes.md"
        ;;
    report) report ;;
    down)
        dc --profile target down -v --remove-orphans || true
        sudo rm -rf "$R"
        ;;
    all) "$0" up && "$0" run && "$0" rollback && "$0" report --out "$OUT" ;;
    *) sed -n '2,3p' "$0" | sed 's/^# //' >&2; exit 1 ;;
esac
